const { readFileSync } = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const context = { window: {} };
for(const file of ['matra-motion.js','matra-update-view.js']) vm.runInNewContext(readFileSync(path.join(__dirname,'../codenotch/ui',file),'utf8'),context);
const tracker = new context.window.MatraMotionTracker();
assert.equal(tracker.reading('claude','session',.12,true),null);
assert.equal(tracker.reading('claude','session',.12,true),null);
assert.equal(tracker.reading('claude','session',.17,true).to,.17);
assert.equal(tracker.reading('claude','session',0,true).to,0);
assert.equal(tracker.reading('claude','session',.8,false),null);
assert.equal(tracker.reading('claude','session',.8,true),null);
assert.equal(tracker.reading('codex','primary',NaN,true),null);
assert.equal(tracker.reading('codex','primary',-.1,true),null);
assert.equal(tracker.reading('claude@other','session',.9,true),null);
assert.equal(tracker.claude([{id:'a',state:'done'}]),false);
assert.equal(tracker.claude([{id:'a',state:'running'}]),false);
assert.equal(tracker.claude([{id:'a',state:'done'}]),true);
assert.equal(tracker.claude([{id:'a',state:'done'}]),false);
assert.equal(tracker.claude([{id:'a',state:'running'}]),false);
assert.equal(tracker.claude([]),false);
assert.equal(tracker.activity([{provider:'codex',state:'done',since:1}]).length,0);
assert.equal(tracker.activity([{provider:'codex',state:'busy',since:2}]).length,0);
assert.equal(tracker.activity([]).length,0);
assert.equal(tracker.activity([{provider:'codex',state:'done',since:3}])[0],'codex');
assert.equal(tracker.activity([{provider:'codex',state:'done',since:3}]).length,0);
const view=context.window.matraUpdateView;
assert.equal(view({}).message,'Not checked yet.');
assert.equal(view({phase:'available',available:'1.8.2'}).command,'download_update');
assert.equal(view({phase:'downloading',total:100,downloaded:25}).percent,25);
assert.equal(view({phase:'downloading'}).busy,true);
assert.equal(view({phase:'ready'}).command,'install_update');
assert.equal(view({phase:'error',available:'1.8.2',message:'Checksum failed'}).message,'Checksum failed');
assert.equal(view({phase:'error'}).command,'check_for_update');
assert.equal(view({phase:'installing'}).busy,true);
assert.equal(view({phase:'updated',message:'Updated to v1.8.2'}).message,'Updated to v1.8.2');
console.log('PASS: 29 assertions for reading deltas, evidence-only completion, deduplication and update states');
